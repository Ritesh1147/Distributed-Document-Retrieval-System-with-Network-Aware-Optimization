"""Generate a docker-compose.yml for an arbitrary S-shard x R-replica topology.

The generated stack runs both architectures side by side against one Redis:

* ``router-distributed`` (host port 8080) over ``S x R`` shard nodes
* ``router-centralized`` (host port 8081) over one full-index node

Each replica ``r`` is placed in zone ``zone<r>``; pass ``--far-zone-profile``
to give one zone a slower simulated link (e.g. ``cross_zone``) so the
network-aware balancer has something to optimise.

    python docker/gen_compose.py --shards 4 --replicas 2 > docker-compose.yml
    docker compose up -d --build --wait
    curl 'localhost:8080/search?q=dairkdark+geasjil'
"""

from __future__ import annotations

import argparse


def node(name: str, cluster: str, shard: int, num_shards: int, zone: str, profile: str) -> str:
    return f"""
  {name}:
    <<: *ddr
    environment:
      <<: *ddr-env
      NODE_ID: {name}
      CLUSTER: {cluster}
      SHARD_ID: "{shard}"
      NUM_SHARDS: "{num_shards}"
      ZONE: {zone}
      ADVERTISE_URL: http://{name}:8000
      NET_PROFILE: {profile}
    healthcheck:
      test: ["CMD", "curl", "-fs", "http://localhost:8000/health"]
      interval: 3s
      timeout: 2s
      retries: 40"""


def router(name: str, cluster: str, port: int, deps: list[str], strategy: str, hedge: str, cache: int,
           max_inflight: int) -> str:
    dep = "".join(f"\n      {d}:\n        condition: service_healthy" for d in deps)
    return f"""
  {name}:
    <<: *ddr
    environment:
      <<: *ddr-env
      ROLE: router
      CLUSTER: {cluster}
      LB_STRATEGY: {strategy}
      HEDGE_MS: "{hedge}"
      CACHE_TTL_S: "{cache}"
      MAX_INFLIGHT: "{max_inflight}"
    ports:
      - "{port}:8000"
    depends_on:{dep}
    healthcheck:
      test: ["CMD", "curl", "-fs", "http://localhost:8000/health"]
      interval: 3s
      timeout: 2s
      retries: 40"""


def generate(shards: int, replicas: int, profile: str, far_zone_profile: str | None, strategy: str,
             hedge: str, cache: int, centralized: bool, max_inflight: int = 0) -> str:
    out = [f"""# Generated by docker/gen_compose.py --shards {shards} --replicas {replicas}
x-ddr: &ddr
  build:
    context: .
    dockerfile: docker/Dockerfile
  image: ddr:latest
  restart: unless-stopped
  cap_add: [NET_ADMIN]   # allows kernel netem via docker/netem.sh
  depends_on:
    redis:
      condition: service_healthy

x-ddr-env: &ddr-env
  REDIS_URL: redis://redis:6379/0

services:
  redis:
    image: redis:7-alpine
    command: ["redis-server", "--save", "", "--appendonly", "no"]
    ports:
      - "6379:6379"
    healthcheck:
      test: ["CMD", "redis-cli", "ping"]
      interval: 2s
      timeout: 2s
      retries: 20"""]
    dist_nodes = []
    for s in range(shards):
        for r in range(replicas):
            name = f"dist-s{s}r{r}"
            prof = far_zone_profile if (far_zone_profile and r == replicas - 1 and replicas > 1) else profile
            out.append(node(name, "distributed", s, shards, f"zone{r}", prof))
            dist_nodes.append(name)
    out.append(router("router-distributed", "distributed", 8080, dist_nodes, strategy, hedge, cache, max_inflight))
    if centralized:
        out.append(node("central-node", "centralized", 0, 1, "zone0", profile))
        out.append(router("router-centralized", "centralized", 8081, ["central-node"], strategy, hedge, cache,
                          max_inflight))
    return "\n".join(out) + "\n"


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--shards", type=int, default=4)
    ap.add_argument("--replicas", type=int, default=2)
    ap.add_argument("--profile", default="datacenter", help="network profile for every node")
    ap.add_argument("--far-zone-profile", default=None, help="profile for the last replica zone")
    ap.add_argument("--strategy", default="latency_aware")
    ap.add_argument("--hedge-ms", default="-1")
    ap.add_argument("--cache-ttl", type=int, default=60)
    ap.add_argument("--max-inflight", type=int, default=0, help="router admission control (0 = off)")
    ap.add_argument("--no-centralized", action="store_true")
    a = ap.parse_args()
    print(generate(a.shards, a.replicas, a.profile, a.far_zone_profile, a.strategy, a.hedge_ms,
                   a.cache_ttl, not a.no_centralized, a.max_inflight), end="")


if __name__ == "__main__":
    main()
